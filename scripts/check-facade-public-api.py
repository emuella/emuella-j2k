#!/usr/bin/env python3
"""Check the `emuella-j2k` facade's public surface against a reviewed snapshot.

The facade re-exports items defined in `emuella-j2k-core` and lower-layer
crates. Rustdoc JSON does not inline cross-crate re-exports, so this check
documents the facade and every workspace crate in its dependency closure, then
follows each re-export into its defining crate. It renders every reachable
field, variant, method, associated item and trait implementation, and fails when:

* a rendered signature names an item that the facade does not itself export,
  other than items from `core`, `alloc` and `std` (an unexported lower-layer or
  core-only item has become reachable); or
* the rendered surface differs from the committed snapshot.

Rustdoc JSON is unstable output. The check uses the repository's pinned
toolchain and enables it only for the documented workspace crates through a
crate-scoped `RUSTC_BOOTSTRAP` value; no nightly toolchain is required. The
format version is pinned below and must be reviewed with each toolchain pin
change.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
FORMAT_VERSION = 61
DEFAULT_PACKAGE = "emuella-j2k"
DEFAULT_SNAPSHOT = ROOT / "docs/emuella-j2k-public-api.txt"
# The snapshot records default features. Every listed feature set must render
# the same surface, so a feature-gated item cannot bypass review.
DEFAULT_FEATURE_SETS = ("", "emuella-j2k/parallel,emuella-j2k/simd")
STANDARD_CRATES = frozenset({"core", "alloc", "std"})
# Stable auto traits are part of the compatibility surface. Toolchain-internal
# marker traits (for example `Freeze` or `StructuralPartialEq`) are not.
AUTO_TRAITS = frozenset(
    {
        ("core", "marker", "Send"),
        ("core", "marker", "Sync"),
        ("core", "marker", "Unpin"),
        ("core", "panic", "unwind_safe", "UnwindSafe"),
        ("core", "panic", "unwind_safe", "RefUnwindSafe"),
    }
)
INTERNAL_TRAITS = frozenset(
    {
        ("core", "marker", "Freeze"),
        ("core", "marker", "StructuralPartialEq"),
        ("core", "marker", "UnsafeUnpin"),
        ("core", "clone", "TrivialClone"),
    }
)
HEADER = (
    "# Reviewed public surface of the emuella-j2k facade, identical with default\n"
    "# features and with the parallel and simd features.\n"
    "# Generated by scripts/check-facade-public-api.py; do not edit by hand.\n"
    "# Refresh with: python3 scripts/check-facade-public-api.py --update\n"
)


class CheckError(Exception):
    """A failure that the check reports without a traceback."""


@dataclass
class Crate:
    name: str
    data: dict[str, Any]
    local_ids: dict[tuple[str, ...], list[str]] = field(default_factory=dict)

    def __post_init__(self) -> None:
        for item_id, summary in self.data["paths"].items():
            if summary["crate_id"] == 0:
                self.local_ids.setdefault(tuple(summary["path"]), []).append(item_id)

    def item(self, item_id: Any) -> dict[str, Any]:
        return self.data["index"][str(item_id)]

    def canonical(self, item_id: Any) -> tuple[str, ...] | None:
        summary = self.data["paths"].get(str(item_id))
        return tuple(summary["path"]) if summary else None


@dataclass
class Surface:
    exported: dict[tuple[str, ...], str]
    facade: str
    lines: list[str] = field(default_factory=list)
    leaks: list[str] = field(default_factory=list)


class Renderer:
    """Render rustdoc JSON types relative to one crate's path table."""

    def __init__(self, surface: Surface, crate: Crate, context: str) -> None:
        self.surface = surface
        self.crate = crate
        self.context = context

    def path_name(self, item_id: Any, written: str) -> str:
        canonical = self.crate.canonical(item_id)
        if canonical is None:
            self.surface.leaks.append(
                f"{self.context}: `{written}` has no public path in {self.crate.name}"
            )
            return f"?{written}"
        exported = self.surface.exported.get(canonical)
        if exported is not None:
            return exported
        rendered = "::".join(canonical)
        if canonical[0] not in STANDARD_CRATES:
            self.surface.leaks.append(
                f"{self.context}: reaches `{rendered}`, which the facade does not export"
            )
        return rendered

    def path(self, value: dict[str, Any]) -> str:
        return self.path_name(value["id"], value["path"]) + self.args(value.get("args"))

    def args(self, value: dict[str, Any] | str | None) -> str:
        if value is None:
            return ""
        if value == "return_type_notation":
            return "(..)"
        if "parenthesized" in value:
            inner = value["parenthesized"]
            output = inner.get("output")
            suffix = f" -> {self.type(output)}" if output else ""
            return "(" + ", ".join(self.type(item) for item in inner["inputs"]) + ")" + suffix
        inner = value["angle_bracketed"]
        parts = [self.generic_arg(item) for item in inner["args"]]
        parts.extend(self.constraint(item) for item in inner["constraints"])
        return "<" + ", ".join(parts) + ">" if parts else ""

    def generic_arg(self, value: Any) -> str:
        if value == "infer":
            return "_"
        if "lifetime" in value:
            return value["lifetime"]
        if "type" in value:
            return self.type(value["type"])
        return self.constant(value["const"])

    @staticmethod
    def constant(value: dict[str, Any]) -> str:
        return value.get("value") or value["expr"]

    def constraint(self, value: dict[str, Any]) -> str:
        name = value["name"] + self.args(value.get("args"))
        binding = value["binding"]
        if "equality" in binding:
            term = binding["equality"]
            rhs = self.type(term["type"]) if "type" in term else self.constant(term["constant"])
            return f"{name} = {rhs}"
        return f"{name}: {self.bounds(binding['constraint'])}"

    def bounds(self, values: list[Any]) -> str:
        return " + ".join(self.bound(item) for item in values)

    def bound(self, value: dict[str, Any]) -> str:
        if "outlives" in value:
            return value["outlives"]
        if "use" in value:
            names = [
                item if isinstance(item, str) else next(iter(item.values()))
                for item in value["use"]
            ]
            return "use<" + ", ".join(names) + ">"
        inner = value["trait_bound"]
        prefix = {"none": "", "maybe": "?", "maybe_const": "~const "}[inner["modifier"]]
        return prefix + self.higher_ranked(inner["generic_params"]) + self.path(inner["trait"])

    def higher_ranked(self, params: list[Any]) -> str:
        return f"for{self.params(params)} " if params else ""

    def type(self, value: Any) -> str:
        if value is None:
            return "()"
        if value == "infer":
            return "_"
        kind, inner = next(iter(value.items()))
        if kind == "resolved_path":
            return self.path(inner)
        if kind in {"generic", "primitive"}:
            return inner
        if kind == "tuple":
            return "(" + ", ".join(self.type(item) for item in inner) + ("," if len(inner) == 1 else "") + ")"
        if kind == "slice":
            return f"[{self.type(inner)}]"
        if kind == "array":
            return f"[{self.type(inner['type'])}; {inner['len']}]"
        if kind == "pat":
            return f"{self.type(inner['type'])} is {inner['__pat_unstable_do_not_use']}"
        if kind == "borrowed_ref":
            lifetime = f"{inner['lifetime']} " if inner["lifetime"] else ""
            mutable = "mut " if inner["is_mutable"] else ""
            return f"&{lifetime}{mutable}{self.type(inner['type'])}"
        if kind == "raw_pointer":
            mutable = "mut" if inner["is_mutable"] else "const"
            return f"*{mutable} {self.type(inner['type'])}"
        if kind == "impl_trait":
            return "impl " + self.bounds(inner)
        if kind == "dyn_trait":
            traits = [
                self.higher_ranked(item["generic_params"]) + self.path(item["trait"])
                for item in inner["traits"]
            ]
            if inner.get("lifetime"):
                traits.append(inner["lifetime"])
            return "dyn " + " + ".join(traits)
        if kind == "function_pointer":
            return (
                self.higher_ranked(inner["generic_params"])
                + self.header(inner["header"])
                + "fn"
                + self.signature(inner["sig"])
            )
        if kind == "qualified_path":
            self_type = self.type(inner["self_type"])
            trait = inner.get("trait")
            base = f"<{self_type} as {self.path(trait)}>" if trait else self_type
            return f"{base}::{inner['name']}{self.args(inner.get('args'))}"
        raise CheckError(f"{self.context}: unsupported rustdoc type kind `{kind}`")

    def params(self, params: list[dict[str, Any]]) -> str:
        rendered = []
        for param in params:
            kind, inner = next(iter(param["kind"].items()))
            if kind == "lifetime":
                outlives = f": {' + '.join(inner['outlives'])}" if inner["outlives"] else ""
                rendered.append(param["name"] + outlives)
            elif kind == "type":
                if inner["is_synthetic"]:
                    continue
                bounds = f": {self.bounds(inner['bounds'])}" if inner["bounds"] else ""
                default = f" = {self.type(inner['default'])}" if inner["default"] else ""
                rendered.append(param["name"] + bounds + default)
            else:
                default = f" = {inner['default']}" if inner.get("default") else ""
                rendered.append(f"const {param['name']}: {self.type(inner['type'])}{default}")
        return "<" + ", ".join(rendered) + ">" if rendered else ""

    def where_clause(self, predicates: list[dict[str, Any]]) -> str:
        rendered = []
        for predicate in predicates:
            kind, inner = next(iter(predicate.items()))
            if kind == "bound_predicate":
                rendered.append(
                    self.higher_ranked(inner["generic_params"])
                    + f"{self.type(inner['type'])}: {self.bounds(inner['bounds'])}"
                )
            elif kind == "lifetime_predicate":
                rendered.append(f"{inner['lifetime']}: {' + '.join(inner['outlives'])}")
            else:
                rhs = inner["rhs"]
                term = self.type(rhs["type"]) if "type" in rhs else self.constant(rhs["constant"])
                rendered.append(f"{self.type(inner['lhs'])} = {term}")
        return " where " + ", ".join(rendered) if rendered else ""

    @staticmethod
    def header(value: dict[str, Any]) -> str:
        parts = []
        if value["is_const"]:
            parts.append("const ")
        if value["is_async"]:
            parts.append("async ")
        if value["is_unsafe"]:
            parts.append("unsafe ")
        abi = value["abi"]
        if abi != "Rust":
            name = abi if isinstance(abi, str) else next(iter(abi))
            parts.append(f'extern "{name}" ')
        return "".join(parts)

    def signature(self, sig: dict[str, Any]) -> str:
        inputs = []
        for name, value in sig["inputs"]:
            if name == "self":
                if value == {"generic": "Self"}:
                    inputs.append("self")
                    continue
                if "borrowed_ref" in value and value["borrowed_ref"]["type"] == {"generic": "Self"}:
                    ref = value["borrowed_ref"]
                    lifetime = f"{ref['lifetime']} " if ref["lifetime"] else ""
                    inputs.append(f"&{lifetime}{'mut ' if ref['is_mutable'] else ''}self")
                    continue
            inputs.append(f"{name}: {self.type(value)}")
        if sig["is_c_variadic"]:
            inputs.append("...")
        output = f" -> {self.type(sig['output'])}" if sig["output"] is not None else ""
        return "(" + ", ".join(inputs) + ")" + output

    def function(self, owner: str, item: dict[str, Any], visibility: str = "pub ") -> str:
        inner = item["inner"]["function"]
        generics = inner["generics"]
        default = " { .. }" if inner["has_body"] and visibility == "" else ""
        return (
            f"{attributes(item)}{visibility}{self.header(inner['header'])}fn {owner}{item['name']}"
            f"{self.params(generics['params'])}{self.signature(inner['sig'])}"
            f"{self.where_clause(generics['where_predicates'])}{default}"
        )


def attributes(item: dict[str, Any]) -> str:
    rendered = []
    for attr in item.get("attrs", []):
        if attr == "non_exhaustive":
            rendered.append("#[non_exhaustive]")
        elif isinstance(attr, dict) and "repr" in attr:
            rendered.append(f"#[repr({json.dumps(attr['repr'], sort_keys=True)})]")
        elif isinstance(attr, dict) and "other" in attr and "doc(hidden)" in attr["other"].replace(" ", ""):
            rendered.append("#[doc(hidden)]")
    if item.get("deprecation"):
        rendered.append("#[deprecated]")
    return " ".join(rendered) + " " if rendered else ""


def named_paths(value: Any, crate: Crate) -> list[tuple[str, ...] | None]:
    """Canonical paths of every item named in a JSON fragment."""
    if isinstance(value, dict):
        found = []
        if "id" in value and "path" in value and isinstance(value["path"], str):
            found.append(crate.canonical(value["id"]))
        for child in value.values():
            found.extend(named_paths(child, crate))
        return found
    if isinstance(value, list):
        return [path for child in value for path in named_paths(child, crate)]
    return []


def facade_impl(inner: dict[str, Any], crate: Crate, exported: dict[tuple[str, ...], str]) -> bool:
    """Whether a facade caller can use this implementation.

    An inherent implementation belongs to the surface when its self type is an
    exported item. A trait implementation belongs when its header names an
    exported item and every item named by its self type is exported or standard,
    so implementations on unexported lower-layer types stay out of scope.
    """
    for_type = inner["for"]
    if inner["trait"] is None:
        return "resolved_path" in for_type and crate.canonical(for_type["resolved_path"]["id"]) in exported
    header = {"for": for_type, "trait": inner["trait"], "generics": inner["generics"]}
    if not any(path in exported for path in named_paths(header, crate)):
        return False
    return all(
        path is not None and (path in exported or path[0] in STANDARD_CRATES)
        for path in named_paths(for_type, crate)
    )


def document(package: str, manifest: Path, target_dir: Path, features: str = "") -> dict[str, Crate]:
    metadata = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--no-deps", "--locked",
             "--manifest-path", str(manifest)],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    members = {item["name"]: item for item in metadata["packages"]
               if item["id"] in metadata["workspace_members"]}
    if package not in members:
        raise CheckError(f"workspace has no package `{package}`")
    closure: list[str] = []
    pending = [package]
    while pending:
        name = pending.pop()
        if name in closure:
            continue
        closure.append(name)
        pending.extend(
            dependency["name"] for dependency in members[name]["dependencies"]
            if dependency["kind"] is None and dependency["name"] in members
        )
    crate_names = []
    for name in closure:
        libraries = [target["name"] for target in members[name]["targets"] if "lib" in target["kind"]]
        if len(libraries) != 1:
            raise CheckError(f"package `{name}` has no single library target")
        crate_names.append(libraries[0].replace("-", "_"))
    env = dict(os.environ)
    env["RUSTC_BOOTSTRAP"] = ",".join(sorted(crate_names))
    env["RUSTDOCFLAGS"] = "-Z unstable-options --output-format json --document-hidden-items"
    env["CARGO_TARGET_DIR"] = str(target_dir)
    env.pop("CARGO_BUILD_TARGET_DIR", None)
    env.pop("CARGO_BUILD_BUILD_DIR", None)
    command = ["cargo", "doc", "--no-deps", "--locked", "--manifest-path", str(manifest)]
    for name in sorted(closure):
        command.extend(["-p", name])
    if features:
        command.extend(["--features", features])
    subprocess.run(command, check=True, env=env)
    return load(target_dir / "doc", crate_names)


def load(directory: Path, crate_names: list[str]) -> dict[str, Crate]:
    crates = {}
    for name in crate_names:
        path = directory / f"{name}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("format_version") != FORMAT_VERSION:
            raise CheckError(
                f"{path} has rustdoc JSON format {data.get('format_version')}; this check "
                f"supports {FORMAT_VERSION}. Review the renderer for the new toolchain pin."
            )
        crates[name] = Crate(name, data)
    return crates


def facade_exports(facade: Crate) -> tuple[dict[tuple[str, ...], str], list[tuple[str, str]]]:
    root = facade.item(facade.data["root"])
    exported: dict[tuple[str, ...], str] = {}
    roots: list[tuple[str, str]] = []
    for item_id in root["inner"]["module"]["items"]:
        item = facade.item(item_id)
        kind, inner = next(iter(item["inner"].items()))
        name = inner["name"] if kind == "use" else item["name"]
        public_name = f"{facade.name}::{name}"
        if kind == "use":
            if inner["is_glob"]:
                raise CheckError(f"{facade.name} has a glob re-export of `{inner['source']}`")
            canonical = facade.canonical(inner["id"]) if inner["id"] is not None else None
            if canonical is None:
                raise CheckError(f"{facade.name} re-export `{inner['source']}` has no public path")
            summary_kind = facade.data["paths"][str(inner["id"])]["kind"]
            if summary_kind == "module":
                raise CheckError(f"{facade.name} re-exports module `{inner['source']}`")
            exported.setdefault(canonical, public_name)
            roots.append((public_name, "::".join(canonical)))
        elif kind == "module":
            raise CheckError(f"{facade.name} exposes module `{public_name}`")
        else:
            canonical = facade.canonical(item_id)
            if canonical is None:
                raise CheckError(f"{facade.name} item `{public_name}` has no public path")
            exported.setdefault(canonical, public_name)
            roots.append((public_name, "::".join(canonical)))
    return exported, roots


def definition(crates: dict[str, Crate], canonical: tuple[str, ...]) -> tuple[Crate, dict[str, Any]]:
    crate = crates.get(canonical[0])
    if crate is None:
        raise CheckError(f"`{'::'.join(canonical)}` is defined outside the documented workspace closure")
    ids = [item_id for item_id in crate.local_ids.get(canonical, []) if item_id in crate.data["index"]]
    if len(ids) != 1:
        raise CheckError(f"cannot locate `{'::'.join(canonical)}` in {crate.name} rustdoc JSON")
    return crate, crate.item(ids[0])


def render_fields(renderer: Renderer, owner: str, crate: Crate, kind: Any) -> list[str]:
    lines = []
    if kind in ("unit", "plain") or kind is None:
        return lines
    if "tuple" in kind:
        for position, field_id in enumerate(kind["tuple"]):
            if field_id is None:
                lines.append(f"{owner}::{position}: private")
                continue
            item = crate.item(field_id)
            renderer.context = f"{owner}::{position}"
            lines.append(f"{attributes(item)}pub {owner}::{position}: {renderer.type(item['inner']['struct_field'])}")
        return lines
    inner = kind.get("plain") or kind.get("struct")
    for field_id in inner["fields"]:
        item = crate.item(field_id)
        renderer.context = f"{owner}::{item['name']}"
        lines.append(f"{attributes(item)}pub {owner}::{item['name']}: {renderer.type(item['inner']['struct_field'])}")
    if inner["has_stripped_fields"]:
        lines.append(f"{owner}: private fields")
    return lines


def render_item(surface: Surface, public_name: str, crate: Crate, item: dict[str, Any]) -> list[str]:
    renderer = Renderer(surface, crate, public_name)
    kind, inner = next(iter(item["inner"].items()))
    prefix = attributes(item)
    if kind == "function":
        return [renderer.function(f"{surface.facade}::", item)]
    generics = inner.get("generics", {"params": [], "where_predicates": []})
    params = renderer.params(generics["params"])
    where = renderer.where_clause(generics["where_predicates"])
    if kind == "struct":
        lines = [f"{prefix}pub struct {public_name}{params}{where}"]
        return lines + render_fields(renderer, public_name, crate, inner["kind"])
    if kind == "union":
        lines = [f"{prefix}pub union {public_name}{params}{where}"]
        return lines + render_fields(renderer, public_name, crate, {"plain": inner})
    if kind == "enum":
        lines = [f"{prefix}pub enum {public_name}{params}{where}"]
        for variant_id in inner["variants"]:
            variant = crate.item(variant_id)
            name = f"{public_name}::{variant['name']}"
            data = variant["inner"]["variant"]
            discriminant = data["discriminant"]
            suffix = f" = {discriminant['value']}" if discriminant else ""
            lines.append(f"{attributes(variant)}{name}{suffix}")
            lines.extend(render_fields(renderer, name, crate, data["kind"]))
        if inner["has_stripped_variants"]:
            lines.append(f"{public_name}: private variants")
        return lines
    if kind == "trait":
        unsafe = "unsafe " if inner["is_unsafe"] else ""
        supertraits = f": {renderer.bounds(inner['bounds'])}" if inner["bounds"] else ""
        lines = [f"{prefix}pub {unsafe}trait {public_name}{params}{supertraits}{where}"]
        for member_id in inner["items"]:
            member = crate.item(member_id)
            renderer.context = f"{public_name}::{member['name']}"
            lines.append(render_associated(renderer, f"{public_name}::", member, visibility=""))
        return lines
    if kind == "type_alias":
        return [f"{prefix}pub type {public_name}{params} = {renderer.type(inner['type'])}{where}"]
    if kind == "constant":
        return [f"{prefix}pub const {public_name}: {renderer.type(inner['type'])} = {renderer.constant(inner['const'])}"]
    if kind == "static":
        mutable = "mut " if inner["is_mutable"] else ""
        return [f"{prefix}pub static {mutable}{public_name}: {renderer.type(inner['type'])}"]
    raise CheckError(f"{public_name}: unsupported exported item kind `{kind}`")


def render_associated(renderer: Renderer, owner: str, item: dict[str, Any], visibility: str) -> str:
    kind, inner = next(iter(item["inner"].items()))
    prefix = attributes(item)
    if kind == "function":
        return renderer.function(owner, item, visibility)
    if kind == "assoc_const":
        value = f" = {inner['value']}" if inner.get("value") else ""
        return f"{prefix}{visibility}const {owner}{item['name']}: {renderer.type(inner['type'])}{value}"
    if kind == "assoc_type":
        bounds = f": {renderer.bounds(inner['bounds'])}" if inner["bounds"] else ""
        value = f" = {renderer.type(inner['type'])}" if inner.get("type") else ""
        params = renderer.params(inner["generics"]["params"])
        return f"{prefix}{visibility}type {owner}{item['name']}{params}{bounds}{value}"
    raise CheckError(f"{owner}{item['name']}: unsupported associated item kind `{kind}`")


def render_impls(surface: Surface, crates: dict[str, Crate]) -> dict[str, set[str]]:
    """Render facade-usable implementations, grouped by exported self type."""
    groups: dict[str, set[str]] = {}
    for crate in crates.values():
        for item in crate.data["index"].values():
            if "impl" not in item["inner"]:
                continue
            inner = item["inner"]["impl"]
            if inner["blanket_impl"] is not None:
                continue
            if not facade_impl(inner, crate, surface.exported):
                continue
            trait_path = crate.canonical(inner["trait"]["id"]) if inner["trait"] else None
            if trait_path in INTERNAL_TRAITS:
                continue
            if inner["is_synthetic"] and trait_path not in AUTO_TRAITS:
                continue
            renderer = Renderer(surface, crate, "impl")
            for_type = renderer.type(inner["for"])
            owner = ""
            if "resolved_path" in inner["for"]:
                owner = surface.exported.get(crate.canonical(inner["for"]["resolved_path"]["id"]), "")
            lines = groups.setdefault(owner, set())
            renderer.context = f"impl for {for_type}"
            params = renderer.params(inner["generics"]["params"])
            where = renderer.where_clause(inner["generics"]["where_predicates"])
            impl_prefix = f"impl{params} " if params else ""
            if inner["trait"] is None:
                for member_id in inner["items"]:
                    member = crate.item(member_id)
                    if member["visibility"] != "public":
                        continue
                    renderer.context = f"{for_type}::{member['name']}"
                    rendered = render_associated(renderer, f"{for_type}::", member, "pub ")
                    lines.add(f"{impl_prefix}{rendered}{where}" if impl_prefix or where else rendered)
                continue
            negative = "!" if inner["is_negative"] else ""
            unsafe = "unsafe " if inner["is_unsafe"] else ""
            trait = renderer.path(inner["trait"])
            impl_line = f"{unsafe}impl{params} {negative}{trait} for {for_type}{where}"
            lines.add(impl_line)
            for member_id in inner["items"]:
                member = crate.item(member_id)
                if "function" in member["inner"]:
                    continue
                renderer.context = f"{impl_line}::{member['name']}"
                lines.add(f"{impl_line} {{ {render_associated(renderer, '', member, '')} }}")
    return groups


def render(crates: dict[str, Crate], facade_name: str) -> Surface:
    facade = crates[facade_name]
    exported, roots = facade_exports(facade)
    surface = Surface(exported, facade_name)
    impls = render_impls(surface, crates)
    for public_name, canonical in sorted(roots):
        crate, item = definition(crates, tuple(canonical.split("::")))
        surface.lines.extend(render_item(surface, public_name, crate, item))
        surface.lines.extend(sorted(impls.pop(public_name, ())))
    for owner in sorted(impls):
        surface.lines.extend(sorted(impls[owner]))
    return surface


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--update", action="store_true", help="rewrite the snapshot from the current source")
    parser.add_argument("--manifest-path", type=Path, default=ROOT / "Cargo.toml")
    parser.add_argument("--package", default=DEFAULT_PACKAGE)
    parser.add_argument("--snapshot", type=Path, default=DEFAULT_SNAPSHOT)
    parser.add_argument(
        "--features",
        action="append",
        help="Cargo feature set that must render the snapshot (repeatable; "
        "default: the facade's reviewed feature sets)",
    )
    parser.add_argument(
        "--target-dir",
        type=Path,
        help="dedicated Cargo target directory (default: <target>/facade-public-api)",
    )
    args = parser.parse_args(argv)
    feature_sets = args.features
    if feature_sets is None:
        feature_sets = list(DEFAULT_FEATURE_SETS) if args.package == DEFAULT_PACKAGE else [""]
    target_dir = args.target_dir
    if target_dir is None:
        base = os.environ.get("CARGO_TARGET_DIR") or str(args.manifest_path.resolve().parent / "target")
        target_dir = Path(base) / "facade-public-api"
    rendered: dict[str, str] = {}
    for index, features in enumerate(feature_sets):
        label = features or "default features"
        try:
            crates = document(
                args.package, args.manifest_path.resolve(), target_dir.resolve() / f"set-{index}", features
            )
            surface = render(crates, args.package.replace("-", "_"))
        except (CheckError, subprocess.CalledProcessError) as error:
            print(f"facade public API check failed ({label}): {error}", file=sys.stderr)
            return 1
        if surface.leaks:
            print(f"facade public API reaches items it does not export ({label}):", file=sys.stderr)
            for leak in sorted(set(surface.leaks)):
                print(f"  {leak}", file=sys.stderr)
            print(
                "Export the item deliberately from the facade, or keep it out of public "
                "fields, signatures and trait implementations of exported items.",
                file=sys.stderr,
            )
            return 1
        rendered[label] = HEADER + "".join(f"{line}\n" for line in surface.lines)
    labels = list(rendered)
    baseline = rendered[labels[0]]
    if args.update:
        args.snapshot.write_text(baseline, encoding="utf-8")
        print(f"updated {args.snapshot} ({baseline.count(chr(10)) - HEADER.count(chr(10))} entries)")
    try:
        committed = args.snapshot.read_text(encoding="utf-8")
    except FileNotFoundError:
        committed = ""
    for label in labels:
        if rendered[label] == committed:
            continue
        diff = difflib.unified_diff(
            committed.splitlines(keepends=True),
            rendered[label].splitlines(keepends=True),
            fromfile=f"{args.snapshot} (committed)",
            tofile=f"current source ({label})",
        )
        sys.stderr.writelines(diff)
        print(
            f"facade public API with {label} differs from the snapshot. Review the diff, "
            "then run `python3 scripts/check-facade-public-api.py --update` and commit the "
            "snapshot with the change. Feature-dependent surface needs a deliberate "
            "snapshot design change.",
            file=sys.stderr,
        )
        return 1
    print(f"facade public API matches {args.snapshot} for: {', '.join(labels)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
