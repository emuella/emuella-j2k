const fn generate_vlc_lookup_table(
    entries: &[HtVlcSourceEntry],
) -> [u16; HT_VLC_LOOKUP_ENTRY_COUNT] {
    let mut words = [0_u16; HT_VLC_LOOKUP_ENTRY_COUNT];
    let mut index = 0;
    while index < HT_VLC_LOOKUP_ENTRY_COUNT {
        let codeword = (index & 0x7f) as u8;
        let context = (index >> 7) as u8;
        let mut entry_index = 0;
        while entry_index < entries.len() {
            let entry = entries[entry_index];
            let mask = ((1_u16 << entry.codeword_len) - 1) as u8;
            if entry.context == context && entry.codeword == (codeword & mask) {
                words[index] = entry.packed_word();
            }
            entry_index += 1;
        }
        index += 1;
    }
    words
}

const HT_VLC_ENCODER_ENTRY_COUNT: usize = 8 * 16 * 16;

const fn generate_vlc_encoder_table(
    entries: &[HtVlcSourceEntry],
) -> [u16; HT_VLC_ENCODER_ENTRY_COUNT] {
    let mut words = [0_u16; HT_VLC_ENCODER_ENTRY_COUNT];
    let mut index = 0;
    while index < HT_VLC_ENCODER_ENTRY_COUNT {
        let context = (index >> 8) as u8;
        let rho = ((index >> 4) & 0x0f) as u8;
        let embedded = (index & 0x0f) as u8;
        if (embedded & rho) == embedded && (rho != 0 || context != 0) {
            let mut best_index = entries.len();
            let mut best_mask_bits = 0_u32;
            let mut entry_index = 0;
            while entry_index < entries.len() {
                let entry = entries[entry_index];
                if entry.context == context && entry.rho == rho {
                    if embedded == 0 {
                        if entry.u_offset == 0 {
                            best_index = entry_index;
                            break;
                        }
                    } else if entry.u_offset == 1
                        && (embedded & entry.exponent_reduction_bits)
                            == entry.embedded_magnitude_bits
                    {
                        let mask_bits = entry.exponent_reduction_bits.count_ones();
                        if best_index == entries.len() || mask_bits >= best_mask_bits {
                            best_index = entry_index;
                            best_mask_bits = mask_bits;
                        }
                    }
                }
                entry_index += 1;
            }
            if best_index < entries.len() {
                let entry = entries[best_index];
                words[index] = ((entry.codeword as u16) << 8)
                    | ((entry.codeword_len as u16) << 4)
                    | entry.exponent_reduction_bits as u16;
            }
        }
        index += 1;
    }
    words
}

